		g('E', "#####", "#....", "#....", "####.", "#....", "#....", "#####");
		g('F', "#####", "#....", "#....", "####.", "#....", "#....", "#....");
		g('G', ".####", "#....", "#....", "#.###", "#...#", "#...#", ".###.");
		g('H', "#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#");
		g('I', "#####", "..#..", "..#..", "..#..", "..#..", "..#..", "#####");
		g('J', "..###", "...#.", "...#.", "...#.", "#..#.", "#..#.", ".##..");
		g('K', "#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#");
		g('L', "#....", "#....", "#....", "#....", "#....", "#....", "#####");
