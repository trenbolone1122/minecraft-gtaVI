package dev.leonida.test.landmark;

import dev.leonida.landmark.LandmarkCommand;
import dev.leonida.landmark.LandmarkGen;
import dev.leonida.landmark.gen.Site;
import dev.leonida.test.TestFilter;
import dev.leonida.world.WorldModule;
import net.fabricmc.fabric.api.client.gametest.v1.FabricClientGameTest;
import net.fabricmc.fabric.api.client.gametest.v1.context.ClientGameTestContext;
import net.fabricmc.fabric.api.client.gametest.v1.context.TestSingleplayerContext;
import net.minecraft.server.level.ServerLevel;

/**
 * Client game tests for the landmark module. Owned by the landmark agent. Run: tools/gpu-test.sh landmark
 *
 * <p>Every site is checked where world generation put it, in the Leonida dimension: the chunks around the site are
 * force-loaded (generated by the real chunk generator, so roads, buildings and trees run first and must keep clear),
 * then {@link LandmarkCommand#check} replays the site against the real terrain and compares blocks, overlap and
 * footprints ("[leonida-landmark] CHECK site PASS|FAIL ..."), and two screenshots are taken from the site's "photo" view
 * (the gtadb in-game photo camera): landmark-SITE-photo at noon and landmark-SITE-night at midnight.
 */
public class LandmarkClientTest implements FabricClientGameTest {
	private static final String IN = "execute in leonida:world/leonida run ";

	@Override
	public void runTest(ClientGameTestContext context) {
		// tools/pod-test.sh landmarkcheck (LEONIDA_TEST_HOST=leonida-build): server-side checks only, no screenshots
		boolean checkOnly = "landmarkcheck".equals(System.getProperty("leonida.test"));
		if (!checkOnly && !TestFilter.enabled("landmark")) return;
		try (TestSingleplayerContext sp = context.worldBuilder().create()) {
			try {
				sp.getConnection().waitForChunksRender();
			} catch (AssertionError e) {
				log("initial chunks still rendering, continuing");
			}
			context.runOnClient(mc -> {
				mc.options.chatVisibility().set(net.minecraft.world.entity.player.ChatVisiblity.HIDDEN);
				mc.options.renderDistance().set(12);
			});
			cmd(sp, "time set 6000");
			cmd(sp, "weather clear");
			cmd(sp, "gamerule advance_time false");
			cmd(sp, "gamerule advance_weather false");
			cmd(sp, "gamemode spectator @a");
			int pass = 0;
			for (Site s : LandmarkGen.SITES) {
				Site.View v = s.views().stream().filter(w -> w.name().equals("photo")).findFirst().orElse(null);
				int camX = v == null ? s.minX : s.originX() + (int) v.x(), camZ = v == null ? s.minZ : s.originZ() + (int) v.z();
				int cx0 = (Math.min(s.minX, camX) - 16) >> 4, cx1 = (Math.max(s.maxX, camX) + 16) >> 4;
				int cz0 = (Math.min(s.minZ, camZ) - 16) >> 4, cz1 = (Math.max(s.maxZ, camZ) + 16) >> 4;
				while ((cx1 - cx0 + 1) * (cz1 - cz0 + 1) > 256) {
					if (cx1 - cx0 > cz1 - cz0) {
						if (camX > s.maxX) cx1--; else cx0++;
					} else if (camZ > s.maxZ) cz1--; else cz0++;
				}
				final int fx0 = cx0, fx1 = cx1, fz0 = cz0, fz1 = cz1, total = (cx1 - cx0 + 1) * (cz1 - cz0 + 1);
				cmd(sp, IN + "forceload remove all");
				cmd(sp, IN + "forceload add " + (fx0 << 4) + " " + (fz0 << 4) + " " + (fx1 << 4) + " " + (fz1 << 4));
				cmd(sp, IN + "tp @a " + (s.minX + s.maxX) / 2 + " 120 " + (s.minZ + s.maxZ) / 2);
				long t0 = System.currentTimeMillis();
				int loaded = 0;
				for (int i = 0; i < 360 && loaded < total; i++) {
					context.waitTicks(10);
					loaded = sp.getServer().computeOnServer(srv -> {
						ServerLevel lvl = srv.getLevel(WorldModule.LEONIDA);
						int n = 0;
						for (int a = fx0; a <= fx1; a++)
							for (int b = fz0; b <= fz1; b++) if (lvl.getChunkSource().getChunkNow(a, b) != null) n++;
						return n;
					});
				}
				log(s.id + ": " + loaded + "/" + total + " chunks generated in " + (System.currentTimeMillis() - t0) + " ms");
				String r = sp.getServer().computeOnServer(srv -> LandmarkCommand.check(srv.getLevel(WorldModule.LEONIDA), s));
				System.out.println("[leonida-landmark] " + r);
				if (r.contains(" PASS ")) pass++;
				if (v != null && !checkOnly) {
					cmd(sp, IN + "execute as @a run leonida_landmark view " + s.id + " photo");
					int fov = LandmarkCommand.fov(s.id, "photo");
					context.runOnClient(mc -> mc.options.fov().set(fov));
					context.getInput().pressKey(o -> o.keyToggleGui);
					context.waitTicks(40);
					try {
						sp.getConnection().waitForChunksRender();
					} catch (AssertionError e) {
						log(s.id + ": chunks still rendering after the wait, shooting anyway");
					}
					context.waitTicks(40);
					context.takeScreenshot("landmark-" + s.id + "-photo");
					// night shot from the same camera: signs, yard lights and windows (time 18000 = midnight)
					cmd(sp, "time set 18000");
					context.waitTicks(40);
					context.takeScreenshot("landmark-" + s.id + "-night");
					cmd(sp, "time set 6000");
					context.waitTicks(20);
					context.getInput().pressKey(o -> o.keyToggleGui);
				}
			}
			log("sites passing the check: " + pass + "/" + LandmarkGen.SITES.size());
			context.runOnClient(mc -> mc.options.fov().set(70));
		}
	}

	private static void cmd(TestSingleplayerContext sp, String c) {
		sp.getServer().runCommand(c);
	}

	private static void log(String msg) {
		System.out.println("[leonida-test] landmark: " + msg);
	}
}
